package Module2;

public class Assignment6 
{
    public static void main(String[] args) 
    {
        //I chose the "for" loop because when I was learning Python, I was taught that "for" loops are generally better to use for counting integers and "while" loops are better suited for other tasks, like looping gameplay.
        for(int i = 1; i <= 100; i++) {
            System.out.println(i);
        }
    }
}

//Notes:
//"i++" can also be written as "i += 1" or "i = i + 1"
